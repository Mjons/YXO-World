// Sample the YXO mark (logo_icononly.png) into 4096 points with gradient positions.
// usage: node marks.mjs  → writes mark.js and mark.png
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const logo = join(here, "..", "logo_icononly.png");
const W = 400,
  H = Math.round((W * 647) / 1024);
const raw = execFileSync(
  "ffmpeg",
  [
    "-v",
    "error",
    "-i",
    logo,
    "-vf",
    `scale=${W}:${H}`,
    "-f",
    "rawvideo",
    "-pix_fmt",
    "rgba",
    "-",
  ],
  { maxBuffer: 1 << 28 },
);

const ink = [];
for (let y = 0; y < H; y++)
  for (let x = 0; x < W; x++) {
    const i = (y * W + x) * 4;
    const [r, g, b, a] = [raw[i], raw[i + 1], raw[i + 2], raw[i + 3]];
    if (a < 140 || r + g + b > 700) continue;
    // cyan (41,190,245) → lime (196,247,138): r tracks the gradient best
    const t = Math.max(0, Math.min(1, (r - 35) / 165));
    ink.push([x, y, t]);
  }

// deterministic shuffle, then take 4096
let s = 11;
const rnd = () => (s = (s * 1664525 + 1013904223) >>> 0) / 4294967296;
for (let i = ink.length - 1; i > 0; i--) {
  const j = Math.floor(rnd() * (i + 1));
  [ink[i], ink[j]] = [ink[j], ink[i]];
}
const N = 4096;
const pts = [];
for (let k = 0; k < N; k++) {
  const [x, y, t] = ink[k % ink.length];
  // centre on the mark, scale so width spans -1..1; jitter within the pixel
  const nx = ((x + rnd()) / W) * 2 - 1;
  const ny = ((y + rnd() - H / 2) / W) * 2;
  pts.push(Math.round(nx * 1000), Math.round(ny * 1000), Math.round(t * 99));
}
writeFileSync(
  join(here, "mark.js"),
  `// generated by marks.mjs from logo_icononly.png: x,y in -1000..1000 (width-normalised), g 0..99\n` +
    `window.MARK = {n:${N},aspect:${(H / W).toFixed(4)},p:[${pts.join(",")}]};\n`,
);
// crisp copy of the mark for the final frames
execFileSync("ffmpeg", [
  "-v",
  "error",
  "-y",
  "-i",
  logo,
  "-vf",
  "scale=720:-1",
  join(here, "mark.png"),
]);
console.log(`ink pixels ${ink.length}, wrote ${N} points`);
